from typing import List

class КалькуляторСуммы:
    def вычислить_сумму(self, числа: List[int]) -> int:
        итог = 0  # Инициализация переменной для хранения суммы
        for число in числа:  # Проход по каждому элементу списка
            итог += число  # Добавление текущего элемента к общей сумме
        return итог  # Возврат итоговой суммы
# Пример использования класса
калькулятор = КалькуляторСуммы()
результат = калькулятор.вычислить_сумму([1, 2, 3, 4, 5])
print("Сумма чисел:", результат)  # Ожидаемый вывод: Сумма чисел: 15
   
