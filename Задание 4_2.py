def подсчет_элементов(список):
    if not список:  # Проверка на пустоту списка
        return 0  # Если список пустой, возвращаем 0
    else:
        return 1 + подсчет_элементов(список[1:])  # Рекурсивный вызов с оставшейся частью списка

# Пример работы программы:
if __name__ == "__main__":
    элементы = [1, 2, 3, 4, 5]  # Ввод
    количество = подсчет_элементов(элементы)  # Вызов функции
    print(количество)  # Ожидаемый вывод: 5
